"""Форматирование денежных сумм и заголовков для отчёта."""


def format_kopeks(kopeks: int) -> str:
    """Переводит сумму в копейках в строку в рублях.

    Тысячи отделяются пробелом, копейки — запятой: 493750 → «4 937,50 ₽».

    Args:
        kopeks: Сумма в копейках.

    Returns:
        Сумма в рублях с двумя знаками после запятой и знаком ₽.
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Выравнивает заголовок по центру строки из знаков «=».

    Args:
        text: Текст заголовка.
        width: Длина итоговой строки в символах.

    Returns:
        Заголовок, дополненный знаками «=» с обеих сторон до длины width.
    """
    return text.center(width, "=")
